test('a display name containing a comment terminator remains metadata, never runtime code', (t) => {
  const root = fixture(t)
  fs.cpSync(path.join(sourceRoot, 'templates'), path.join(root, 'templates'), { recursive: true })
  const label = 'Device */ throw new Error("name injection") /*'
  const created = createPlugin(root, 'comment-name', 'example.comment-name', label)
  assert.equal(JSON.parse(fs.readFileSync(path.join(created, 'manifest.json'))).name, label)
  const source = fs.readFileSync(path.join(created, 'src/index.cjs'), 'utf8')
  assert.equal(source.includes(label), false)
  const result = spawnSync(process.execPath, ['--test', path.join(created, 'test/plugin.test.cjs')], { encoding: 'utf8' })
  assert.equal(result.status, 0, result.stdout + result.stderr)
})
